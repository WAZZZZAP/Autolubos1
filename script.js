const buttons = document.querySelectorAll(".grid button");
const langButtons = document.querySelectorAll(".lang-switch button");

function updateLanguage(lang) {
    currentLang = lang;
    const t = translations[lang];

    // Update all text elements
    Object.keys(elements).forEach(key => {
        const element = elements[key];
        if (element && t[key]) {
            element.innerText = t[key];
        }
    });

    // Update calculator buttons
    buttons.forEach(btn => {
        const type = btn.dataset.type;
        if (type && t.buttons[type]) {
            btn.innerText = t.buttons[type];
            btn.onclick = () => {
                if (elements.result) {
                    elements.result.innerHTML = `
                        <strong>${t.buttons[type]}</strong><br>
                        ${t.prices[type]}
                    `;
                }
            };
        }
    });

    // Update active language button
    langButtons.forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
    });

    // Save to localStorage
    localStorage.setItem("lang", lang);

    // Update panorama section (if already initialized)
    if (typeof renderPanorama === "function") {
        renderPanorama();
    }
}

// Initialize language
document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("lang") || "lt";

    // Add click events to language buttons
    langButtons.forEach(btn => {
        btn.addEventListener("click", () => {
            updateLanguage(btn.dataset.lang);
        });
    });

    // Lightbox functionality
    const lightbox = document.getElementById("lightbox");
    const lightboxImg = document.getElementById("lightbox-img");
    const galleryImages = document.querySelectorAll(".gallery-item img");

    if (lightbox && lightboxImg) {
        galleryImages.forEach(img => {
            img.addEventListener("click", () => {
                lightboxImg.src = img.src;
                lightbox.style.display = "flex";
            });
        });

        window.closeLightbox = function() {
            lightbox.style.display = "none";
        };
    }

    // Set initial calculator result
    if (elements.result && buttons.length > 0) {
        const t = translations[currentLang];
        elements.result.innerHTML = `
            <strong>${t.buttons.hatchback}</strong><br>
            ${t.prices.hatchback}
        `;
    }

    // ================= PANORAMA SECTION =================
    const panoramaTabs = document.querySelectorAll("#panoramaTabs .tab-btn");
    const panoramaTabContent = document.getElementById("panoramaTabContent");
    const panoramaAccordion = document.getElementById("panoramaAccordion");
    const panoramaPrices = document.getElementById("panoramaPrices");

    let activePanoramaTab = "jam";

    window.renderPanorama = function () {
        const t = translations[currentLang];
        if (!t || !t.panoramaTitle) return;

        const titleEl = document.getElementById("panoramaTitle");
        const introEl = document.getElementById("panoramaIntro");
        const stepsTitleEl = document.getElementById("panoramaStepsTitle");
        const pricesTitleEl = document.getElementById("panoramaPricesTitle");
        const ctaEl = document.getElementById("panoramaCta");

        if (titleEl) titleEl.innerText = t.panoramaTitle;
        if (introEl) introEl.innerText = t.panoramaIntro;
        if (stepsTitleEl) stepsTitleEl.innerText = t.panoramaStepsTitle;
        if (pricesTitleEl) pricesTitleEl.innerText = t.panoramaPricesTitle;
        if (ctaEl) ctaEl.innerText = t.panoramaCta;

        // Tabs labels
        panoramaTabs.forEach(btn => {
            const key = btn.dataset.tab;
            if (t.panoramaTabs[key]) {
                btn.innerText = t.panoramaTabs[key];
            }
            btn.classList.toggle("active", key === activePanoramaTab);
        });

        // Active tab content
        const tab = t.panoramaTabContent[activePanoramaTab];
        if (tab && panoramaTabContent) {
            panoramaTabContent.innerHTML = `
                <h4>${tab.title}</h4>
                <ul>${tab.points.map(p => `<li>${p}</li>`).join("")}</ul>
            `;
        }

        // Accordion
        if (panoramaAccordion) {
            const accItems = panoramaAccordion.querySelectorAll(".acc-item");
            accItems.forEach((item, i) => {
                const step = t.panoramaSteps[i];
                if (!step) return;
                item.querySelector(".acc-header").innerText = step.title;
                item.querySelector(".acc-body p").innerText = step.text;
            });
        }

        // Prices
        if (panoramaPrices) {
            panoramaPrices.innerHTML = t.panoramaPrices.map(p => `
                <div class="panorama-price-item">
                    <span class="p-name">${p.name}</span>
                    <span class="p-value">${p.value}</span>
                </div>
            `).join("");
        }
    };

    // Tabs click
    panoramaTabs.forEach(btn => {
        btn.addEventListener("click", () => {
            activePanoramaTab = btn.dataset.tab;
            window.renderPanorama();
        });
    });

    // Accordion click
    if (panoramaAccordion) {
        panoramaAccordion.querySelectorAll(".acc-header").forEach(header => {
            header.addEventListener("click", () => {
                const item = header.parentElement;
                const isOpen = item.classList.contains("open");
                panoramaAccordion.querySelectorAll(".acc-item").forEach(i => i.classList.remove("open"));
                if (!isOpen) item.classList.add("open");
            });
        });
    }

    // Render everything
    window.renderPanorama();
    updateLanguage(savedLang);
});